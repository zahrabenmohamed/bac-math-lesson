CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(80)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE chapters (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code   VARCHAR(60)  NOT NULL UNIQUE,
    title  VARCHAR(200) NOT NULL,
    status VARCHAR(20)  NOT NULL DEFAULT 'draft'
);

CREATE TABLE lessons (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id BIGINT       NOT NULL REFERENCES chapters (id),
    code       VARCHAR(60)  NOT NULL UNIQUE,
    part       INT          NOT NULL,
    position   INT          NOT NULL,
    title      VARCHAR(200) NOT NULL,
    kind       VARCHAR(20)  NOT NULL DEFAULT 'LESSON',
    status     VARCHAR(20)  NOT NULL DEFAULT 'draft'
);

-- payload: what the client sees. answer: server-only (correct answer + per-option feedback).
CREATE TABLE exercises (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(60) NOT NULL UNIQUE,
    type     VARCHAR(20) NOT NULL,
    skill    VARCHAR(80) NOT NULL,
    payload  TEXT        NOT NULL,
    answer   TEXT        NOT NULL,
    solution TEXT        NOT NULL,
    hint     TEXT        NOT NULL
);

CREATE TABLE steps (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id   BIGINT      NOT NULL REFERENCES lessons (id),
    position    INT         NOT NULL,
    type        VARCHAR(20) NOT NULL,
    content     TEXT,
    exercise_id BIGINT REFERENCES exercises (id),
    UNIQUE (lesson_id, position)
);

CREATE TABLE attempts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT  NOT NULL REFERENCES users (id),
    exercise_id BIGINT  NOT NULL REFERENCES exercises (id),
    answer      TEXT    NOT NULL,
    correct     BOOLEAN NOT NULL,
    hint_used   BOOLEAN NOT NULL,
    time_ms     INT,
    at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_attempts_user_at ON attempts (user_id, at);

CREATE TABLE lesson_progress (
    user_id      BIGINT NOT NULL REFERENCES users (id),
    lesson_id    BIGINT NOT NULL REFERENCES lessons (id),
    steps_done   INT    NOT NULL DEFAULT 0,
    completed_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (user_id, lesson_id)
);

CREATE TABLE exercise_mastery (
    user_id        BIGINT  NOT NULL REFERENCES users (id),
    exercise_id    BIGINT  NOT NULL REFERENCES exercises (id),
    streak_correct INT     NOT NULL DEFAULT 0,
    ever_wrong     BOOLEAN NOT NULL DEFAULT FALSE,
    mastered       BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (user_id, exercise_id)
);

CREATE TABLE user_stats (
    user_id          BIGINT PRIMARY KEY REFERENCES users (id),
    xp               INT NOT NULL DEFAULT 0,
    level            INT NOT NULL DEFAULT 1,
    streak_days      INT NOT NULL DEFAULT 0,
    last_active_date DATE
);
